import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CORE_SKILL_REFERENCES, CORE_SKILL_TOPICS, SKILL_OWNER_FILES } from "../packages/cli/src/skill-reference.ts";
import { isContinuousIntegration } from "./build-packages.mjs";
import { fencedCodeBlocks } from "./markdown-fences.mjs";
import { checkSkillMarkdownLinks, isLocalMarkdownLink, markdownLinks } from "./skill-markdown-links.mjs";

const generatedMarker = "<!-- Generated by scripts/generate-cli-skill.mjs from canonical documents. -->";
const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Read section boundaries outside code fences, including nested subsections. */
export function selectSkillSections(markdown, requested, file) {
  const fences = fencedCodeBlocks(markdown);
  const headings = [...markdown.matchAll(/^(#{1,6})[ \t]+[^\r\n]+/gmu)]
    .filter((match) => !fences.some((fence) => match.index >= fence.blockStart && match.index < fence.blockEnd))
    .map((match) => ({text: match[0].trimEnd(), level: match[1].length, start: match.index}));
  return requested.map((heading) => {
    const matches = headings.filter((entry) => entry.text === heading);
    if (matches.length !== 1) throw new Error(`${file}: expected exactly one canonical heading '${heading}', found ${matches.length}; update the skill topic roster with the canonical section`);
    const selected = matches[0];
    const end = headings.find((entry) => entry.start > selected.start && entry.level <= selected.level)?.start ?? markdown.length;
    return markdown.slice(selected.start, end).trimEnd();
  }).join("\n\n");
}

/** All content is derived before any generated file is written. */
export async function generateCliSkillFiles(root = repositoryRoot) {
  const manifest = JSON.parse(await readFile(join(root, "packages/cli/package.json"), "utf8"));
  if (typeof manifest.version !== "string" || manifest.version.length === 0) throw new Error("the CLI package must declare its version before generating its skill reference");
  const sources = new Map();
  async function document(file) {
    if (!sources.has(file)) sources.set(file, await readFile(join(root, file), "utf8"));
    return sources.get(file);
  }
  const output = new Map();
  for (const file of Object.values(SKILL_OWNER_FILES)) {
    output.set(`packages/cli/skill/${file}`, await document(`docs/${file}`));
  }
  const references = {...CORE_SKILL_TOPICS, ...CORE_SKILL_REFERENCES};
  const destinations = new Map([
    ["docs/language-charter.md", "index.md"],
    ["docs/core-standard.md", "contract.md"],
    ["docs/standard-library.md", "api.md"],
    ...Object.entries(CORE_SKILL_REFERENCES).flatMap(([name, reference]) => reference.sources.map(source => [source.file, `${name}.md`])),
  ]);
  for (const [topic, definition] of Object.entries(references)) {
    const sections = [];
    for (const source of definition.sources) {
      const markdown = await document(source.file);
      let selected = source.headings ? selectSkillSections(markdown, source.headings, source.file) : markdown.trimEnd();
      if (source.endBefore !== undefined) {
        const boundary = selected.indexOf(source.endBefore);
        if (boundary < 0 || selected.indexOf(source.endBefore, boundary + 1) >= 0) {
          throw new Error(`${source.file}: expected one reference boundary '${source.endBefore}'`);
        }
        selected = selected.slice(0, boundary).trimEnd();
      }
      for (const link of markdownLinks(selected).reverse()) {
        if (!isLocalMarkdownLink(link.target) || link.target.startsWith("#")) continue;
        const split = link.target.indexOf("#");
        const pathname = split < 0 ? link.target : link.target.slice(0, split);
        const fragment = split < 0 ? "" : link.target.slice(split);
        const canonical = posix.normalize(posix.join(posix.dirname(source.file), decodeURIComponent(pathname)));
        const destination = destinations.get(canonical);
        if (destination === undefined) throw new Error(`${source.file}: local reference '${link.target}' has no packaged reference in the roster`);
        selected = selected.slice(0, link.start) + destination + fragment + selected.slice(link.end);
      }
      sections.push(`Source: ${source.file}\n\n${selected}`);
    }
    output.set(`packages/cli/skill/reference/${topic}.md`, [
      generatedMarker,
      `# VelarScript Core reference: ${definition.title}`,
      `Packaged with @velarscript/cli ${manifest.version}.`,
      Object.hasOwn(CORE_SKILL_TOPICS, topic)
        ? `Read this topic with \`velar skill core ${topic}\`. Discover adjacent topics with \`velar skill core topics\`.`
        : "This supporting contract is bundled for offline links from the Core topics. [Core reference index](index.md).",
      ...sections,
      "",
    ].join("\n\n").trimEnd() + "\n");
  }
  output.set("packages/cli/skill/reference/index.md", [
    generatedMarker,
    "# VelarScript Core reference index",
    `Packaged with @velarscript/cli ${manifest.version}.`,
    "Read a topic with `velar skill core <topic>`; `velar skill core topics` lists the same task-oriented vocabulary.",
    "## Topics",
    ...Object.entries(CORE_SKILL_TOPICS).map(([topic, definition]) => `- [${definition.title}](${topic}.md)`),
    "## Supporting contracts",
    ...Object.entries(CORE_SKILL_REFERENCES).map(([topic, definition]) => `- [${definition.title}](${topic}.md)`),
    "",
  ].join("\n\n").trimEnd() + "\n");
  const broken = checkSkillMarkdownLinks(output);
  if (broken.length > 0) throw new Error(`CLI skill links must resolve inside the packaged payload:\n${broken.join("\n")}`);
  return output;
}

/** Local builds synchronize; CI and --check reject drift without rewriting it. */
export async function synchronizeCliSkill(root = repositoryRoot, {check = false, ci = isContinuousIntegration()} = {}) {
  const files = await generateCliSkillFiles(root);
  const stale = [];
  for (const [file, text] of files) {
    const committed = await readFile(join(root, file), "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (committed !== text) stale.push(file);
  }
  const reference = join(root, "packages/cli/skill/reference");
  const entries = await readdir(reference, {withFileTypes: true}).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  const retired = [];
  for (const entry of entries) {
    const file = `packages/cli/skill/reference/${entry.name}`;
    if (files.has(file)) continue;
    if (!entry.isFile() || !(await readFile(join(root, file), "utf8")).startsWith(generatedMarker)) {
      throw new Error(`${file}: the generated reference directory contains an unmanaged file`);
    }
    retired.push(file);
  }
  if ((check || ci) && (stale.length > 0 || retired.length > 0)) {
    throw new Error([
      "the committed CLI skill payload is stale; checking and CI do not rewrite it:",
      ...stale.map((file) => `  ${file}`),
      ...retired.map((file) => `  ${file} (topic is absent from the roster)`),
      "Run 'node scripts/generate-cli-skill.mjs' after updating the canonical documents, then commit the generated payload.",
    ].join("\n"));
  }
  for (const file of stale) {
    await mkdir(dirname(join(root, file)), {recursive: true});
    await writeFile(join(root, file), files.get(file), "utf8");
  }
  for (const file of retired) await unlink(join(root, file));
  return {files: files.size, updated: stale, removed: retired};
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arguments_ = process.argv.slice(2);
  if (arguments_.length > 1 || (arguments_.length === 1 && arguments_[0] !== "--check" && arguments_[0] !== "--build")) {
    process.stderr.write("Usage: node scripts/generate-cli-skill.mjs [--check|--build]\n");
    process.exitCode = 2;
  } else {
    try {
      const result = await synchronizeCliSkill(repositoryRoot, {check: arguments_[0] === "--check"});
      // npm forwards lifecycle output during pack --json; keep its stdout machine-readable.
      process.stderr.write(`CLI skill payload: ${result.files} files, ${result.updated.length} updated, ${result.removed.length} retired\n`);
    } catch (error) {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    }
  }
}
